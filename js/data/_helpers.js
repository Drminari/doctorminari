// 모든 칼럼이 모이는 목록 (posts-*.js 파일들이 여기에 추가합니다)
const POSTS = [];

// 카테고리별 데이터 파일에서 사용: 칼럼들을 한 번에 등록
function registerPosts(category, list) {
  list.forEach(p => POSTS.push({ ...p, category }));
}

// "편집포인트" 표시 (나중에 실제 내용으로 교체할 자리)
// 사용 예) body: ["본문 문장", ed("본인 데이터·참고문헌")]
const ed = text => `<span class='ed'>편집포인트: ${text}</span>`;
